ORDER BY CANCELLED,DIVERTED;


-- SUMMURY OF CANCELLED & DIVERTED FLIGHTS
SELECT
    COUNT(*) AS total_flights,
    COUNT(*) FILTER (WHERE CANCELLED = 1) AS cancelled_flights,
    COUNT(*) FILTER (WHERE DIVERTED = 1) AS diverted_flights
FROM flights;


--7.JOINING TABLES FLIGHTS & AIRLINES
SELECT
    f.AIRLINE,
    a.AIRLINE AS AIRLINE_NAME,
    f.FLIGHT_NUMBER,
    f.DEPARTURE_DELAY,
    f.ARRIVAL_DELAY
FROM flights AS f
LEFT JOIN airlines AS a
    ON f.AIRLINE = a.IATA_CODE
LIMIT 20;

-- 8.JOINING FLIGHTS WITH ORIGIN AND DESTINATION AIRPORTS
SELECT
    f.FLIGHT_NUMBER,
    f.AIRLINE,
    origin.AIRPORT AS ORIGIN_AIRPORT_NAME,
    destination.AIRPORT AS DESTINATION_AIRPORT_NAME,
    f.DEPARTURE_DELAY,
    f.ARRIVAL_DELAY
FROM flights AS f
LEFT JOIN airports AS origin
    ON f.ORIGIN_AIRPORT = origin.IATA_CODE
LEFT JOIN airports AS destination
    ON f.DESTINATION_AIRPORT = destination.IATA_CODE
LIMIT 20;

