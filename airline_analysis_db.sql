-- BQ-1)Which airlines operate the most flights?

SELECT 
      a.AIRLINE AS AIRLINE_NAME ,
	  COUNT (*)  AS TOTAL_FLIGHTS
	  FROM FLIGHTS AS f
	  LEFT JOIN AIRLINES AS a
	  on f.AIRLINE=a.IATA_CODE
	  GROUP BY a.AIRLINE 
	  ORDER BY TOTAL_FLIGHTS DESC;


-- BQ-2-Which airlines have the highest cancellation rates?

SELECT
    a.AIRLINE AS AIRLINE_NAME,
    COUNT(*) AS TOTAL_FLIGHTS,
    COUNT(*) FILTER (WHERE f.CANCELLED = 1) AS CANCELLED_FLIGHTS,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE f.CANCELLED = 1) / COUNT(*),
        2
    ) AS CANCELLATION_RATE
FROM flights AS f
LEFT JOIN airlines AS a
    ON f.AIRLINE = a.IATA_CODE
GROUP BY a.AIRLINE
ORDER BY CANCELLATION_RATE DESC;

-- BQ-3- Which airlines experience the highest average arrival delays?
SELECT
    a.AIRLINE AS AIRLINE_NAME,
    COUNT(f.ARRIVAL_DELAY) AS FLIGHTS_WITH_ARRIVAL_DELAY,
    ROUND(AVG(f.ARRIVAL_DELAY)::NUMERIC, 2) AS AVG_ARRIVAL_DELAY
FROM flights AS f
LEFT JOIN airlines AS a
    ON f.AIRLINE = a.IATA_CODE
WHERE f.CANCELLED = 0
  AND f.DIVERTED = 0
  AND f.ARRIVAL_DELAY IS NOT NULL
GROUP BY a.AIRLINE
ORDER BY AVG_ARRIVAL_DELAY DESC;

