-- 4.VALIDATING IMPORTED DATA
SELECT
    YEAR,
    MONTH,
    COUNT(*) AS total_flights
FROM flights
GROUP BY YEAR, MONTH
ORDER BY YEAR, MONTH;

-- 5.CHECKING FOR MISSING VALUES
SELECT
    COUNT(*) AS total_rows,
    COUNT(*) FILTER (WHERE AIRLINE IS NULL) AS missing_airline,
    COUNT(*) FILTER (WHERE ORIGIN_AIRPORT IS NULL) AS missing_origin,
    COUNT(*) FILTER (WHERE DESTINATION_AIRPORT IS NULL) AS missing_destination,
    COUNT(*) FILTER (WHERE DEPARTURE_DELAY IS NULL) AS missing_departure_delay,
    COUNT(*) FILTER (WHERE ARRIVAL_DELAY IS NULL) AS missing_arrival_delay
FROM flights;

-- 6.CHECKING CANCELLED & DIVERTED RECORD 
SELECT CANCELLED,DIVERTED,COUNT(*) AS TOTAL_FLIGHTS
FROM FLIGHTS 
